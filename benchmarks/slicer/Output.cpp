GCodeDigest gcode_digest(const std::string& path)
{
    boost::nowide::ifstream file(path, std::ios::binary);
    if (!file.is_open())
        throw std::runtime_error("cannot read " + path);
    GCodeDigest digest {fnv_offset, 0};
    const auto  add = [&digest](std::string_view text) {
        digest.hash = fnv1a(digest.hash, text);
        digest.bytes += text.size();
    };
    bool        skipped = false;
    std::string line;
    while (std::getline(file, line)) {
        const std::size_t generated = skipped ? std::string::npos : line.find("; generated by ");
        if (generated != std::string::npos) {
            add(std::string_view(line).substr(0, generated));
            skipped = true;
            continue;
        }
        add(line);
        // getline() sets eof only for a last line without a line break.
        if (!file.eof())
            add("\n");
    }
    if (file.bad())
        throw std::runtime_error("cannot read " + path);
    return digest;
}

std::uint64_t model_hash(const Model& model)
{
    std::uint64_t hash = fnv_offset;
    for (const ModelObject* object : model.objects) {
        for (const ModelVolume* volume : object->volumes) {
            hash = fnv1a(hash, volume->mesh().its.vertices);
            hash = fnv1a(hash, volume->mesh().its.indices);
            hash = fnv1a(hash, volume->get_matrix());
        }
        for (const ModelInstance* instance : object->instances)
            hash = fnv1a(hash, instance->get_matrix());
    }
    return hash;
}

WorkStats work_of(const GCodeProcessorResult& result, std::uint64_t gcode_bytes)
{
    WorkStats                          work;
    std::set<unsigned int>             layers;
    std::array<std::uint64_t, erCount> role_moves {};
    std::array<double, erCount>        role_volume {};
    for (const GCodeProcessorResult::MoveVertex& move : result.moves) {
        if (move.type == EMoveType::Travel) {
            ++work.moves;
            ++work.travel_moves;
        } else if (move.type == EMoveType::Extrude) {
            ++work.moves;
            layers.insert(move.layer_id);
            const double diameter = result.filament_diameters.at(move.extruder_id);
            const double volume   = move.delta_extruder * PI * diameter * diameter / 4.;
            work.extrusion_mm3 += volume;
            ++role_moves[move.extrusion_role];
            role_volume[move.extrusion_role] += volume;
        }
    }
    work.layers      = layers.size();
    work.gcode_bytes = gcode_bytes;
    for (std::size_t role = 0; role < erCount; ++role)
        if (role_moves[role] > 0) {
            work.metrics[std::string("moves.") + role_keys[role]]         = double(role_moves[role]);
            work.metrics[std::string("extrusion_mm3.") + role_keys[role]] = role_volume[role];
        }
    return work;
}

